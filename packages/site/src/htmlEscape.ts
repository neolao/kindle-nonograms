/**
 * Escapes text for safe use as HTML text content or inside a quoted
 * attribute value. Shared by every page renderer in this package.
 */
export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
